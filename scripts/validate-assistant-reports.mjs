import fs from "node:fs/promises"
import assert from "node:assert/strict"

export async function validateAssistantReports(database, asUser, { employee, otherEmployee, supervisor, foreignSupervisor }) {
  await database.exec(await fs.readFile("supabase/migrations/202611050004_daily_report_notification_type.sql", "utf8"))
  const sql = await fs.readFile("supabase/migrations/202611050005_assistant_daily_reports.sql", "utf8")
  await database.exec(sql); await database.exec(sql)
  const date = (await database.query("select (now() at time zone o.timezone)::date::text as day from public.profiles p join public.organizations o on o.id = p.organization_id where p.id = $1", [employee])).rows[0].day
  const call = (actor, query, params = []) => asUser(actor, () => database.query(query, params))
  const note = (actor, key, text = "Finished three campaign graphics.") => call(actor, "select public.save_daily_report_note($1, $2, $3) as id", [date, text, key])
  const key = "e0000000-0000-4000-8000-000000000001"
  const first = (await note(employee, key)).rows[0].id
  assert.equal((await note(employee, key)).rows[0].id, first, "Retry duplicated a note")
  await assert.rejects(note(employee, key, "Different update"), { code: "22023" })
  const report = async () => (await database.query("select * from public.daily_reports where author_id = $1 and report_date = $2", [employee, date])).rows[0]
  let saved = await report()
  assert.equal(saved.notes_revision, 1)
  assert.equal(saved.status, "draft")
  assert.equal((await call(employee, "select body from public.daily_report_notes where report_id = $1", [saved.id])).rows[0].body, "Finished three campaign graphics.", "Author could not reload a saved note")
  assert.equal((await call(supervisor, "select * from public.daily_reports where id = $1", [saved.id])).rows.length, 0, "Supervisor saw a private draft")
  assert.equal((await call(otherEmployee, "select * from public.daily_report_notes where report_id = $1", [saved.id])).rows.length, 0, "Another user saw private notes")
  await assert.rejects(call(otherEmployee, "update public.daily_reports set body = 'tampered' where id = $1", [saved.id]), { code: "42501" })
  const save = (revision, body = "Today I finished three campaign graphics.") => call(employee, "select public.save_daily_report_body($1, $2, $3)", [date, body, revision])
  await assert.rejects(save(0), { code: "40001" })
  await save(saved.revision)
  saved = await report()
  assert.equal(saved.body_notes_revision, saved.notes_revision)
  await note(employee, "e0000000-0000-4000-8000-000000000002", "Attended the marketing meeting.")
  saved = await report()
  const submit = (recipient, revision = saved.revision) => call(employee, "select public.submit_daily_report($1, $2, $3)", [date, recipient, revision])
  await assert.rejects(submit(supervisor), { code: "22023" })
  await save(saved.revision, "Finished three graphics and attended the marketing meeting.")
  saved = await report()
  await assert.rejects(submit(foreignSupervisor), { code: "42501" })
  await assert.rejects(submit(otherEmployee), { code: "42501" })
  await assert.rejects(submit(employee), { code: "42501" })
  await assert.rejects(submit(supervisor, saved.revision - 1), { code: "40001" })
  const eligible = (await call(employee, "select * from public.list_daily_report_supervisors()")).rows
  assert(eligible.some(person => person.id === supervisor))
  assert(!eligible.some(person => person.id === foreignSupervisor || person.id === employee))
  const tasksBefore = (await database.query("select id, status from public.tasks order by id")).rows
  await submit(supervisor)
  saved = await report()
  assert.equal(saved.status, "submitted")
  assert.equal(saved.recipient_id, supervisor)
  assert.equal((await call(supervisor, "select body from public.daily_reports where id = $1", [saved.id])).rows[0].body, saved.body)
  assert.equal((await call(supervisor, "select * from public.daily_report_notes where report_id = $1", [saved.id])).rows.length, 0, "Receiver saw private raw notes")
  assert.equal((await call(otherEmployee, "select * from public.daily_reports where id = $1", [saved.id])).rows.length, 0)
  assert.equal((await call(foreignSupervisor, "select * from public.daily_reports where id = $1", [saved.id])).rows.length, 0)
  await assert.rejects(save(saved.revision), { code: "23514" })
  await assert.rejects(submit(supervisor), { code: "23514" })
  assert.equal((await database.query("select count(*)::int as n from public.notifications where entity_id = $1 and type = 'daily_report_submitted'", [saved.id])).rows[0].n, 1)
  assert.deepEqual((await database.query("select id, status from public.tasks order by id")).rows, tasksBefore, "Sending a report changed task statuses")
  await note(supervisor, "e0000000-0000-4000-8000-000000000003", "Reviewed the team's work and prepared the CEO update.")
  assert.equal((await call(employee, "select * from public.daily_reports where author_id = $1", [supervisor])).rows.length, 0, "Supervisor's own report was exposed")
  await database.query("update public.profiles set status = 'inactive', deactivated_at = now() where id = $1", [supervisor])
  await assert.rejects(note(supervisor, "e0000000-0000-4000-8000-000000000004"), { code: "42501" })
  await database.query("update public.profiles set status = 'active', deactivated_at = null where id = $1", [supervisor])
  for(let i=0;i<60;i++) assert.equal((await call(employee, "select public.claim_assistant_request() as allowed")).rows[0].allowed, true)
  assert.equal((await call(employee, "select public.claim_assistant_request() as allowed")).rows[0].allowed, false)
  assert.equal((await call(supervisor, "select public.claim_assistant_request() as allowed")).rows[0].allowed, true)
  assert.equal((await database.query("select has_function_privilege('anon', 'public.save_daily_report_note(date,text,uuid)', 'execute') as allowed")).rows[0].allowed, false)
  await assert.rejects(call(employee, "select * from private.assistant_request_usage"), { code: "42501" })
  await database.exec(sql)
  assert.equal((await report()).body, saved.body, "Reapplying migration changed a report")
  console.log("Assistant reports validated: own-note isolation, idempotent retries, draft privacy, explicit supervisor-only sending, tenant isolation, stale-edit and submitted locks, supervisor's own report, unchanged task workflow, deduplicated notifications and distributed AI allowance.")
}
