import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react"
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"

const restore = vi.hoisted(() => vi.fn())
const remove = vi.hoisted(() => vi.fn())
vi.mock("@/app/clients/actions", () => ({ restoreClientFromTrash: restore, permanentlyDeleteClientFromTrash: remove, createClientRecord: vi.fn() }))
import { ClientTrashActions } from "./client-trash-actions"
import { ClientDirectory } from "./client-directory"
const originalShowModal = Object.getOwnPropertyDescriptor(HTMLDialogElement.prototype, "showModal")
const originalClose = Object.getOwnPropertyDescriptor(HTMLDialogElement.prototype, "close")
beforeEach(() => {
  vi.clearAllMocks(); restore.mockResolvedValue(undefined); remove.mockResolvedValue({ deleted: true })
  Object.defineProperty(HTMLDialogElement.prototype, "showModal", { configurable: true, value: function (this: HTMLDialogElement) { this.setAttribute("open", "") } })
  Object.defineProperty(HTMLDialogElement.prototype, "close", { configurable: true, value: function (this: HTMLDialogElement) { this.removeAttribute("open") } })
})
afterEach(() => {
  cleanup()
  if (originalShowModal) Object.defineProperty(HTMLDialogElement.prototype, "showModal", originalShowModal)
  else Reflect.deleteProperty(HTMLDialogElement.prototype, "showModal")
  if (originalClose) Object.defineProperty(HTMLDialogElement.prototype, "close", originalClose)
  else Reflect.deleteProperty(HTMLDialogElement.prototype, "close")
})

describe("Client Trash menu", () => {
  it("keeps actions in the menu and requests confirmation before deletion", async () => {
    const deleted = vi.fn()
    render(<ClientTrashActions clientId="client-1" clientName="Example client" canDelete onDeleted={deleted} />)
    expect(screen.queryByRole("menuitem")).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole("button", { name: "Trash actions for Example client" }))
    expect(await screen.findByRole("menuitem", { name: "Restore client" })).toBeInTheDocument()
    expect(remove).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole("menuitem", { name: "Delete permanently" }))
    expect(await screen.findByRole("dialog", { name: "Permanently delete Example client?" })).toBeInTheDocument()
    expect(screen.getByRole("button", { name: "Delete permanently" })).toBeDisabled()
    expect(screen.getByText(/Google Drive copies remain/)).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText("Type Example client to confirm"), { target: { value: "Wrong client" } })
    expect(screen.getByRole("button", { name: "Delete permanently" })).toBeDisabled()
    expect(remove).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole("button", { name: "Cancel" }))
    expect(deleted).not.toHaveBeenCalled()
    expect(restore).not.toHaveBeenCalled()
  })
  it("limits non-administrators to restoration and prevents repeated pending actions", async () => {
    let finish: () => void = () => {}
    restore.mockImplementation(() => new Promise<void>(resolve => { finish = resolve }))
    render(<ClientTrashActions clientId="client-1" clientName="Example client" canDelete={false} onDeleted={vi.fn()} />)
    fireEvent.click(screen.getByRole("button", { name: "Trash actions for Example client" }))
    expect(await screen.findByRole("menuitem", { name: "Restore client" })).toBeInTheDocument()
    expect(screen.queryByRole("menuitem", { name: "Delete permanently" })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole("menuitem", { name: "Restore client" }))
    await waitFor(() => expect(restore).toHaveBeenCalledOnce())
    expect(restore.mock.calls[0][0].get("clientId")).toBe("client-1")
    expect(screen.getByRole("button", { name: "Trash actions for Example client" })).toBeDisabled()
    await act(async () => finish())
    await waitFor(() => expect(screen.getByRole("button", { name: "Trash actions for Example client" })).toBeEnabled())
  })
  it("requires a matching name and shows pending state until permanent deletion finishes", async () => {
    let finish: (result: { deleted: boolean }) => void = () => {}
    remove.mockImplementation(() => new Promise(resolve => { finish = resolve }))
    const deleted = vi.fn()
    render(<ClientTrashActions clientId="client-1" clientName="Example client" canDelete onDeleted={deleted} />)
    fireEvent.click(screen.getByRole("button", { name: "Trash actions for Example client" }))
    fireEvent.click(await screen.findByRole("menuitem", { name: "Delete permanently" }))
    const dialog = await screen.findByRole("dialog")
    fireEvent.change(screen.getByLabelText("Type Example client to confirm"), { target: { value: "Example client" } })
    expect(screen.getByRole("button", { name: "Delete permanently" })).toBeEnabled()
    fireEvent.submit(dialog.querySelector("form")!)
    await waitFor(() => expect(remove).toHaveBeenCalledOnce())
    expect(remove.mock.calls[0][1].get("clientId")).toBe("client-1")
    expect(remove.mock.calls[0][1].get("confirmationName")).toBe("Example client")
    expect(screen.getByRole("button", { name: "Deleting…" })).toBeDisabled()
    expect(screen.getByRole("button", { name: "Cancel" })).toBeDisabled()
    expect(deleted).not.toHaveBeenCalled()
    await act(async () => finish({ deleted: true }))
    await waitFor(() => expect(deleted).toHaveBeenCalledOnce())
  })
  it("keeps the card and confirmation open on a failed deletion", async () => {
    remove.mockResolvedValue({ error: "Nothing was deleted. Retry." })
    const deleted = vi.fn()
    render(<ClientTrashActions clientId="client-1" clientName="Example client" canDelete onDeleted={deleted} />)
    fireEvent.click(screen.getByRole("button", { name: "Trash actions for Example client" }))
    fireEvent.click(await screen.findByRole("menuitem", { name: "Delete permanently" }))
    fireEvent.change(screen.getByLabelText("Type Example client to confirm"), { target: { value: "Example client" } })
    fireEvent.submit(screen.getByRole("dialog").querySelector("form")!)
    expect(await screen.findByRole("alert")).toHaveTextContent("Nothing was deleted")
    expect(deleted).not.toHaveBeenCalled()
    expect(screen.getByRole("button", { name: "Delete permanently" })).toBeEnabled()
  })
  it("removes only the deleted card while keeping the Trash search and remaining count", async () => {
    render(<ClientDirectory clients={[]} trashedClients={[
      { id: "client-1", name: "Example one", description: null, status: "active", deleted_at: "2026-11-10T01:00:00Z" },
      { id: "client-2", name: "Example two", description: null, status: "active", deleted_at: "2026-11-10T01:00:00Z" },
    ]} canManageTrash canPermanentlyDelete initialView="trash" />)
    const search = screen.getByRole("searchbox", { name: "Search clients or account managers" })
    fireEvent.change(search, { target: { value: "Example" } })
    expect(screen.queryByRole("button", { name: "Restore client" })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole("button", { name: "Trash actions for Example one" }))
    fireEvent.click(await screen.findByRole("menuitem", { name: "Delete permanently" }))
    fireEvent.change(screen.getByLabelText("Type Example one to confirm"), { target: { value: "Example one" } })
    fireEvent.submit(screen.getByRole("dialog").querySelector("form")!)
    await waitFor(() => expect(screen.queryByRole("heading", { name: "Example one" })).not.toBeInTheDocument())
    expect(screen.getByRole("heading", { name: "Example two" })).toBeInTheDocument()
    expect(search).toHaveValue("Example")
    expect(screen.getByRole("link", { name: "Trash 1" })).toBeInTheDocument()
    expect(screen.getByText("Client and linked work permanently deleted from Jota.")).toHaveAttribute("role", "status")
  })
})
